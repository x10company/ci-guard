#!/usr/bin/env bash
# Свежи ли своды правил. Ничего не меняет, только смотрит.
#
# Зачем отдельно от mashina.sh: тот настраивает и обновляет, а этот отвечает на
# вопрос «надо ли». Обновляться посреди задачи нельзя — критерий приёмки уедет
# под ногами, — поэтому сперва смотрят, а решают потом.
#
#   bash svody.sh
#
# Код возврата: 0 — диск свежий, 1 — отстал, 2 — посмотреть не удалось.
#
# Версий три, и путать их дорого:
#   опубликовано  что лежит на GitHub;
#   на диске      что скачано этой машиной;
#   в сессии      с чем работает конкретный чат.
#
# ВНИМАНИЕ: /reload-plugins двигает не только третью. Замер 11.09.2026 на macOS
# (Claude Code 2.1.263) показал, что одна эта команда сходила в маркетплейс и
# сменила УСТАНОВЛЕННУЮ версию — без claude plugin update. Замер 07.09.2026 на
# Windows 2.1.252 говорил обратное. Отчего зависит, пока не выяснено, поэтому
# считаем так: reload МОЖЕТ сходить в сеть. Внутри идущей задачи не выполнять.
# Третью этот скрипт узнать не может: он не внутри чата. Её печатает сам чат,
# когда вызывает свод, — в пути загрузки стоит номер.
set -u

BAZA="$HOME/.claude/plugins"
MARKET="$BAZA/marketplaces/x10company"
USTANOVLENO="$BAZA/installed_plugins.json"

[ -d "$MARKET/.git" ] || { echo "  маркетплейс не подключён: запусти mashina.sh"; exit 2; }
[ -f "$USTANOVLENO" ] || { echo "  плагины не установлены: запусти mashina.sh"; exit 2; }

git -C "$MARKET" fetch -q origin 2>/dev/null || {
  echo "  до GitHub не достучаться — сужу по тому, что скачано ранее"; }

otstal=0
neyasno=0

# Разбираем JSON разбором, а не sed-диапазоном до "]": на однострочном файле
# диапазон не кончается там, где кончается запись плагина, и head -1 отдаёт
# ЧУЖУЮ версию — молча, без ошибки. Поймано направлением 11.09.2026.
PY=$(command -v python3 || command -v python) || {
  echo "  нет python — разобрать список установленных плагинов нечем"; exit 2; }

# Читает version из plugin.json, переданного ДОВОДОМ, а не вводом:
# стандартный ввод у питона занят самим текстом программы.
versiya_iz_json() {
  "$PY" - "$1" <<'KONEC'
import json, sys
try:
    print(json.loads(sys.argv[1])["version"])
except Exception:
    print("")
KONEC
}
versiya_na_diske() {
  "$PY" - "$USTANOVLENO" "$1" <<'KONEC'
import json, sys
try:
    d = json.load(open(sys.argv[1], encoding="utf-8"))
    print(d["plugins"]["%s@x10company" % sys.argv[2]][0]["version"])
except Exception:
    print("")
KONEC
}

echo "  плагин           опубликовано  на диске"
for p in x10-obshchie x10-hozyaystvo; do
  # Тоже питоном, а не sed: обратный слэш в замене на пути из bash в файл
  # однажды уже превратился в управляющий символ, и подстановка вернула мусор.
  tekst=$(git -C "$MARKET" show "origin/main:plugins/$p/.claude-plugin/plugin.json" 2>/dev/null)
  tam=$(versiya_iz_json "$tekst")
  tut=$(versiya_na_diske "$p")
  # Незнание — не отставание. Прежде пустой ответ сравнивался с версией, не
  # совпадал и объявлялся «ОТСТАЛ»: скрипт толкал обновляться, ничего не
  # проверив. Третий исход обязателен.
  if [ -z "$tam" ] || [ -z "$tut" ]; then
    [ -n "$tam" ] || tam="не видно"
    [ -n "$tut" ] || tut="не видно"
    metka="СРАВНИТЬ НЕ С ЧЕМ"; neyasno=1
  elif [ "$tam" = "$tut" ]; then
    metka="свежо"
  else
    metka="ОТСТАЛ"; otstal=1
  fi
  printf '  %-16s %-13s %-12s %s
' "$p" "$tam" "$tut" "$metka"
done

if [ "$neyasno" -eq 1 ]; then
  cat <<'KONEC'

  Сравнить не с чем: какую-то из версий прочитать не удалось.
  Причины бывают разные — GitHub недоступен, плагин переименован в
  маркетплейсе, ветка другая, клон битый. Обновляться на этом основании НЕ надо:
  скрипт не знает, отстали вы или нет, и врать в эту сторону не станет.

  Посмотреть руками:
    claude plugin list
    git -C ~/.claude/plugins/marketplaces/x10company log --oneline -1 origin/main
KONEC
  exit 2
fi

echo
if [ "$otstal" -eq 1 ]; then
  cat <<'KONEC'
  Диск этой машины отстал. Обновлять — МЕЖДУ задачами, не внутри:
  задача принимается против той версии свода, с которой начата.

    claude plugin update x10-obshchie@x10company
    claude plugin update x10-hozyaystvo@x10company

  После этого в каждом уже открытом чате — /reload-plugins, и только если
  чат СЕЙЧАС не в середине задачи: эта команда сама может сходить в сеть
  и сменить версию, а не просто перечитать диск.

  Новому чату она не нужна: он берёт с диска то, что там лежит.
KONEC
  exit 1
fi

cat <<'KONEC'
  Диск свежий. Но это ещё не значит, что свеж ЧАТ.

  Чат держит текст, загруженный при запуске или при последней /reload-plugins.
  Узнать его версию можно единственным способом — попросить сессию вызвать свод
  и назвать каталог загрузки: номер стоит прямо в пути.

      .../plugins/cache/x10company/x10-obshchie/2.22.0/skills/hod-raboty
                                               ^^^^^^ вот она

  Номер в списке плагинов про это не говорит: он показывает скачанное.
KONEC
exit 0
