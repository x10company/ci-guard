#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Проверяет, что направление подключено, а не просто заведено.

Зачем барьером, а не напоминанием. Порядок подключения записан в своде, но свод
не применяет себя сам: свежая сессия в пустом репозитории начинает писать код, а
не обвешивать его проверками. Замер по семи направлениям: сам прошёл порядок
ровно один. Остальным говорили словами — и одно всё равно пропустило файл.

Напоминание лечит забывчивость того, кто его прочитал. Барьер лечит её у всех.

Что требуем — ровно две строки в начале CLAUDE.md, и обе не формальность:

  уровень проверки   без него направление получает полный процесс по умолчанию,
                     а он рассчитан на боевые ключи и распоряжение средствами;
  куда писать        свежая сессия читает CLAUDE.md раньше любого свода, и если
                     там не сказано, она пойдёт искать собеседника по именам.

Репозиторий-инструмент направлением не является: в вызывающем guard.yml для
него ставят napravlenie: false, и проверка не запускается вовсе. Явный отказ
лучше молчаливого исключения списком: список расходится, а отказ виден в файле.
"""
import io
import os
import re
import sys

sys.stdout.reconfigure(encoding="utf-8")

KOREN = sys.argv[1] if len(sys.argv) > 1 else "."
FAYL = os.path.join(KOREN, "CLAUDE.md")
URUVNI = ("полный", "средний", "легкий")


def ravnyat(s):
    """Вниз по регистру и без ё: направление пишет строку как хочет."""
    return s.lower().replace(chr(1105), chr(1077))


def otkaz(*stroki):
    print("")
    print("  ОСТАНОВЛЕНО: направление не подключено до конца.")
    print("")
    for s in stroki:
        print("  " + s)
    print("")
    print("  Порядок целиком — свод hod-raboty, раздел «Новое направление».")
    print("")
    return 1


def main():
    if not os.path.isfile(FAYL):
        return otkaz(
            "В корне нет CLAUDE.md. Это не документация, а первое, что читает",
            "любая сессия в этом каталоге, — и единственное место, где записаны",
            "предметные запреты направления.",
            "",
            "Первыми двумя строками:",
            "",
            "    Уровень проверки: <лёгкий|средний|полный> — потому что <довод>",
            "    Переписка со специалистом: задачами в этом репозитории (gh issue list)",
        )

    with io.open(FAYL, encoding="utf-8", errors="replace") as f:
        stroki = f.read().split(chr(10))[:15]

    uroven = None
    kuda = False
    for s in stroki:
        r = ravnyat(s)
        if "ровень проверки" in r and uroven is None:
            for u in URUVNI:
                if u in r:
                    uroven = u
        if "переписка со специалистом" in r:
            kuda = True

    bedy = []
    if uroven is None:
        bedy.append("Нет строки с уровнем проверки среди первых 15 строк CLAUDE.md.")
        bedy.append("Уровень определяется четырьмя вопросами из свода и записывается так:")
        bedy.append("")
        bedy.append("    Уровень проверки: <лёгкий|средний|полный> — потому что <довод>")
        bedy.append("")
        bedy.append("Довод обязателен: он и есть проверка, что вопросы задавали.")
    if not kuda:
        if bedy:
            bedy.append("")
        bedy.append("Нет строки о том, куда писать специалисту. Без неё свежая сессия")
        bedy.append("ищет собеседника по именам и адресам — 07.09.2026 такая сессия")
        bedy.append("потратила на это двенадцать команд, а ответ был в одну строку:")
        bedy.append("")
        bedy.append("    Переписка со специалистом: задачами в этом репозитории (gh issue list)")

    if bedy:
        return otkaz(*bedy)

    print("  подключение: уровень %s, куда писать — сказано" % uroven)
    return 0


if __name__ == "__main__":
    sys.exit(main())
